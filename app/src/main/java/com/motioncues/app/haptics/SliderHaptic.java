package com.motioncues.app.haptics;

/** Ползунок, у каждого из которых свой характер вибрации на делениях. */
public enum SliderHaptic {
    /** Размер точек: от укола в одну точку к мягкой волне по всему корпусу. */
    SIZE,
    /** Количество точек: столько быстрых «шариков», сколько точек. */
    COUNT,
    /** Непрозрачность: чем плотнее точки, тем плотнее тик. */
    OPACITY,
    /** Чувствительность: чем выше, тем сильнее вибрация. */
    SENSITIVITY
}
