package com.motioncues.app.haptics;

/** Моменты, в которые приложение отвечает вибрацией. */
public enum HapticEffect {
    /** Эффект включён: нарастание и чёткий щелчок. */
    CUES_ON,
    /** Эффект выключен: затухание и мягкий тик. */
    CUES_OFF,
    /** Тумблер включён. */
    TOGGLE_ON,
    /** Тумблер выключен. */
    TOGGLE_OFF,
    /** Выбор варианта в группе кнопок. */
    SELECT,
    /** Деление ползунка. */
    SLIDER_TICK,
    /** Крайнее деление ползунка — упор. */
    SLIDER_EDGE
}
