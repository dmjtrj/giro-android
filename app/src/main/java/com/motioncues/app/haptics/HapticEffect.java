package com.motioncues.app.haptics;

/** Моменты, в которые приложение отвечает вибрацией. */
public enum HapticEffect {
    /** Эффект включён: падающий металлический шарик. */
    CUES_ON,
    /** Эффект выключен: шарик укатывается, замедляется и замирает. */
    CUES_OFF,
    /** Включён режим «Как на iPhone»: два чистых удара — «успех» в духе Taptic Engine. */
    IPHONE_ON,
    /** Тумблер включён. */
    TOGGLE_ON,
    /** Тумблер выключен. */
    TOGGLE_OFF,
    /** Выбор варианта в группе кнопок. */
    SELECT
}
